-- ACT06: registros de asistencia por COT y visitas técnicas con GPS.
-- Crear/aplicar esta migración en Supabase antes de habilitar el flujo.
-- No modifica ni elimina tablas existentes.

CREATE TABLE IF NOT EXISTS public.registros_asistencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajador_id bigint NOT NULL
        REFERENCES public.trabajadores(id) ON DELETE RESTRICT,
    coordinador_id bigint NOT NULL
        REFERENCES public.trabajadores(id) ON DELETE RESTRICT,
    cot text NOT NULL CHECK (length(btrim(cot)) > 0),
    proyecto text NOT NULL CHECK (length(btrim(proyecto)) > 0),
    fecha_entrada timestamptz NOT NULL DEFAULT clock_timestamp(),
    fecha_salida timestamptz,
    CONSTRAINT registros_asistencia_salida_posterior
        CHECK (fecha_salida IS NULL OR fecha_salida >= fecha_entrada)
);

-- Un trabajador no puede tener dos turnos abiertos al mismo tiempo.
CREATE UNIQUE INDEX IF NOT EXISTS registros_asistencia_un_turno_abierto_uidx
    ON public.registros_asistencia (trabajador_id)
    WHERE fecha_salida IS NULL;

CREATE INDEX IF NOT EXISTS registros_asistencia_fecha_entrada_idx
    ON public.registros_asistencia (fecha_entrada DESC);

CREATE TABLE IF NOT EXISTS public.visitas_tecnicas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordinador_id bigint NOT NULL
        REFERENCES public.trabajadores(id) ON DELETE RESTRICT,
    latitud double precision NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud double precision NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    precision_m double precision CHECK (precision_m IS NULL OR precision_m >= 0),
    idempotency_key uuid NOT NULL UNIQUE,
    registrado_en timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS visitas_tecnicas_registrado_en_idx
    ON public.visitas_tecnicas (registrado_en DESC);

ALTER TABLE public.registros_asistencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visitas_tecnicas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.registros_asistencia FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.visitas_tecnicas FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.registros_asistencia, public.visitas_tecnicas TO service_role;

CREATE OR REPLACE FUNCTION public.registrar_entrada_asistencia(
    p_trabajador_id bigint,
    p_coordinador_id bigint,
    p_cot text,
    p_proyecto text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    nuevo public.registros_asistencia%ROWTYPE;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.trabajadores
        WHERE id = p_coordinador_id
          AND perfil = 'coordinador'
          AND lower(btrim(estado)) = 'activo'
    ) THEN
        RAISE EXCEPTION 'COORDINADOR_NO_AUTORIZADO' USING ERRCODE = '42501';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.trabajadores
        WHERE id = p_trabajador_id
          AND perfil = 'trabajador'
          AND lower(btrim(estado)) = 'activo'
    ) THEN
        RAISE EXCEPTION 'TRABAJADOR_NO_ACTIVO' USING ERRCODE = 'P0001';
    END IF;

    IF p_cot IS NULL OR length(btrim(p_cot)) = 0
       OR p_proyecto IS NULL OR length(btrim(p_proyecto)) = 0 THEN
        RAISE EXCEPTION 'COT_Y_PROYECTO_OBLIGATORIOS' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO public.registros_asistencia
        (trabajador_id, coordinador_id, cot, proyecto)
    VALUES
        (p_trabajador_id, p_coordinador_id, btrim(p_cot), btrim(p_proyecto))
    RETURNING * INTO nuevo;

    RETURN jsonb_build_object(
        'id', nuevo.id,
        'trabajador_id', nuevo.trabajador_id,
        'cot', nuevo.cot,
        'proyecto', nuevo.proyecto,
        'fecha_entrada', nuevo.fecha_entrada
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_salida_asistencia(
    p_trabajador_id bigint,
    p_coordinador_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    actualizado public.registros_asistencia%ROWTYPE;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.trabajadores
        WHERE id = p_coordinador_id
          AND perfil = 'coordinador'
          AND lower(btrim(estado)) = 'activo'
    ) THEN
        RAISE EXCEPTION 'COORDINADOR_NO_AUTORIZADO' USING ERRCODE = '42501';
    END IF;

    UPDATE public.registros_asistencia
       SET fecha_salida = clock_timestamp()
     WHERE trabajador_id = p_trabajador_id
       AND fecha_salida IS NULL
    RETURNING * INTO actualizado;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'NO_HAY_ENTRADA_ABIERTA' USING ERRCODE = 'P0001';
    END IF;

    RETURN jsonb_build_object(
        'id', actualizado.id,
        'trabajador_id', actualizado.trabajador_id,
        'cot', actualizado.cot,
        'proyecto', actualizado.proyecto,
        'fecha_entrada', actualizado.fecha_entrada,
        'fecha_salida', actualizado.fecha_salida
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_visita_tecnica(
    p_coordinador_id bigint,
    p_latitud double precision,
    p_longitud double precision,
    p_precision_m double precision,
    p_idempotency_key uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    nueva public.visitas_tecnicas%ROWTYPE;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.trabajadores
        WHERE id = p_coordinador_id
          AND perfil = 'coordinador'
          AND lower(btrim(estado)) = 'activo'
    ) THEN
        RAISE EXCEPTION 'COORDINADOR_NO_AUTORIZADO' USING ERRCODE = '42501';
    END IF;

    IF p_latitud IS NULL OR p_latitud NOT BETWEEN -90 AND 90
       OR p_longitud IS NULL OR p_longitud NOT BETWEEN -180 AND 180
       OR p_idempotency_key IS NULL
       OR (p_precision_m IS NOT NULL AND p_precision_m < 0) THEN
        RAISE EXCEPTION 'COORDENADAS_INVALIDAS' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO public.visitas_tecnicas
        (coordinador_id, latitud, longitud, precision_m, idempotency_key)
    VALUES
        (p_coordinador_id, p_latitud, p_longitud, p_precision_m, p_idempotency_key)
    ON CONFLICT (idempotency_key) DO UPDATE
        SET idempotency_key = EXCLUDED.idempotency_key
    RETURNING * INTO nueva;

    RETURN jsonb_build_object(
        'id', nueva.id,
        'latitud', nueva.latitud,
        'longitud', nueva.longitud,
        'precision_m', nueva.precision_m,
        'registrado_en', nueva.registrado_en
    );
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_entrada_asistencia(bigint, bigint, text, text)
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_salida_asistencia(bigint, bigint)
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_visita_tecnica(bigint, double precision, double precision, double precision, uuid)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_entrada_asistencia(bigint, bigint, text, text)
    TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_salida_asistencia(bigint, bigint)
    TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_visita_tecnica(bigint, double precision, double precision, double precision, uuid)
    TO service_role;
